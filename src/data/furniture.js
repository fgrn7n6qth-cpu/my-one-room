export function getFurniturePreviewSize(type, scale = 1) {
  const size = furnitureMetricMap[type] ?? furnitureMetricMap.chair
  return [size.width * scale, size.depth * scale, size.height * scale]
}

export function getFurniturePlacement3D(item, roomDimensions) {
  const [width, depth, height] = getFurniturePreviewSize(item.type, item.scale ?? 1)
  return {
    width,
    depth,
    height,
    x: -roomDimensions.width / 2 + ((item.x ?? 18) / 100) * roomDimensions.width + width / 2,
    z: -roomDimensions.depth / 2 + ((item.y ?? 24) / 100) * roomDimensions.depth + depth / 2,
  }
}

export function getScaledBounds(type, scale = 1, roomDimensions) {
  const size = furnitureMetricMap[type] ?? furnitureMetricMap.chair
  return {
    w: (size.width * scale / roomDimensions.width) * 100,
    h: (size.depth * scale / roomDimensions.depth) * 100,
  }
}

export function getOBBCorners(cx, cy, w, h, rotDeg) {
  const rad = (rotDeg * Math.PI) / 180
  const cos = Math.cos(rad)
  const sin = Math.sin(rad)
  const hw = w / 2
  const hh = h / 2
  return [
    { x: cx + cos * (-hw) - sin * (-hh), y: cy + sin * (-hw) + cos * (-hh) },
    { x: cx + cos * hw - sin * (-hh), y: cy + sin * hw + cos * (-hh) },
    { x: cx + cos * hw - sin * hh, y: cy + sin * hw + cos * hh },
    { x: cx + cos * (-hw) - sin * hh, y: cy + sin * (-hw) + cos * hh },
  ]
}

export function satOverlap(cornersA, cornersB) {
  for (let poly = 0; poly < 2; poly++) {
    const corners = poly === 0 ? cornersA : cornersB
    for (let i = 0; i < corners.length; i++) {
      const j = (i + 1) % corners.length
      const axisX = corners[j].x - corners[i].x
      const axisY = corners[j].y - corners[i].y
      let minA = Infinity
      let maxA = -Infinity
      let minB = Infinity
      let maxB = -Infinity
      for (const p of cornersA) {
        const proj = p.x * axisX + p.y * axisY
        if (proj < minA) minA = proj
        if (proj > maxA) maxA = proj
      }
      for (const p of cornersB) {
        const proj = p.x * axisX + p.y * axisY
        if (proj < minB) minB = proj
        if (proj > maxB) maxB = proj
      }
      if (maxA <= minB || maxB <= minA) return false
    }
  }
  return true
}
